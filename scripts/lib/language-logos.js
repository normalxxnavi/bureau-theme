/**
 * Los logotipos de los lenguajes para Bureau Icons: el logotipo oficial de cada
 * uno, simplificado a la rejilla de 16 px (filas 1–11; debajo va la franja de
 * clasificación) y en el color de su marca. Son dibujos propios hechos a mano
 * píxel a píxel a partir de cada logotipo; las marcas son de sus dueños y aquí
 * solo dicen de qué lenguaje es un archivo.
 *
 * En `rows`: '#' (y las diagonales J L F 7 de pixel-art.js) es el primer color,
 * 'a' el segundo y 'b' el tercero. `draw` (en lugar de `rows`) devuelve los
 * polígonos de cada color, para las formas que no son de píxeles (las órbitas
 * de React). `colors` son los oficiales: scripts/icons.js los aclara u oscurece
 * lo justo para que se vean en los temas oscuros y en CONTROL Astral.
 *
 * Los lenguajes sin logotipo propio (JSON, YAML, XML, LaTeX, Razor, XAML…)
 * siguen con su etiqueta de expediente.
 */

const K = require('./glyph-kit');

/** @typedef {import('./glyph-kit').Poly} Poly */
/** @typedef {{name: string, logo: string, colors: string[], rows?: string[], draw?: () => Poly[][]}} Logo */

/** Las órbitas de React: tres elipses (0°, 60° y 120°) alrededor del núcleo. */
function atom() {
  /** Elipse como polígono, sin dos vértices seguidos a la misma altura (los bordes rectos han de caer en píxeles enteros). */
  const ellipse = (/** @type {number} */ rx, /** @type {number} */ ry, /** @type {number} */ deg, /** @type {boolean} */ inner) => {
    const rot = (deg * Math.PI) / 180;
    /** @type {Poly} */
    const p = [];
    for (let i = 0; i < 48; i++) {
      const t = 0.0731 + (i / 48) * Math.PI * 2;
      const x = rx * Math.cos(t);
      const y = ry * Math.sin(t);
      p.push([8 + x * Math.cos(rot) - y * Math.sin(rot), 6.5 + x * Math.sin(rot) + y * Math.cos(rot)]);
    }
    return inner ? K.cut(...p) : K.poly(...p);
  };
  const rings = [0, 60, 120].flatMap((deg) => [ellipse(7, 2.6, deg, false), ellipse(5.9, 1.55, deg, true)]);
  return [[...rings, K.rect(7, 5, 2, 3)]];
}

