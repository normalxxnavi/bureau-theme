/** @type {BoardMoment[]} */
const MOMENTS = /** @type {BoardMoment[]} */ (Object.keys(LINES));

/** De madrugada (de 0:00 a 4:59) el Consejo prefiere hablar de dormir. @param {Date} date */
const isLateNight = (date) => date.getHours() < 5;

/**
 * Un mensaje al azar de un momento, en el idioma de VS Code (español si
 * empieza por «es», inglés en cualquier otro caso), distinto del anterior.
 * @param {BoardMoment} moment
 * @param {string} language `vscode.env.language`
 * @param {() => number} [random]
 * @param {string} [previous] el último mensaje mostrado
 */
function pickLine(moment, language, random = Math.random, previous) {
  const lines = LINES[moment];
  const lang = language.toLowerCase().startsWith('es') ? 1 : 0;
  let i = Math.floor(random() * lines.length) % lines.length;
  if (lines.length > 1 && lines[i][lang] === previous) i = (i + 1) % lines.length;
  return lines[i][lang];
}

module.exports = { LINES, MOMENTS, isLateNight, pickLine };
